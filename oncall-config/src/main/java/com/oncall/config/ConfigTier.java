package com.oncall.config;

/**
 * 配置项的可见性与可变性分级。
 *
 * <p>这是「配置外置」这条架构约束的核心：原则上凡是能做成前端可交互配置的都不得
 * 硬编码在后端，但有三类例外必须留在后端，否则会出安全事故或物理上根本改不了。
 *
 * <p>分级的判据不是「重不重要」，而是「改了之后会发生什么」。
 */
public enum ConfigTier {

    /**
     * 前端可见、可改、保存后热生效，无需重启、无需重建索引。
     *
     * <p>绝大多数调优参数属于这一类：召回候选数、Top-N、相似度阈值、RRF k、
     * 各类超时、预算上限、放权等级、告警聚合窗口等。
     */
    RUNTIME_HOT,

    /**
     * 前端可见、可改，但改动会触发一个**显式的迁移流程**（通常是全量重建索引），
     * 且在新流程跑完之前新旧值不能混用。
     *
     * <p>典型：切片大小、embedding 模型。前端必须把这一点讲清楚，
     * 不能让人以为点一下「保存」就生效了。
     */
    REQUIRES_MIGRATION,

    /**
     * 仅后端可见可改，前端**既不展示也不可编辑**。
     *
     * <p>三类必须落在这一级：
     * <ol>
     *   <li><b>兜底机制配置</b>——按架构约束显式排除在前端之外。
     *       兜底是系统最后一道防线，如果它本身可以在前端被改坏，
     *       那么「兜底」就不成立了。</li>
     *   <li><b>DDL 绑定项</b>——如向量维度、距离函数、索引类型。
     *       它们写死在建表语句的列定义里，改了必须重建表，
     *       不是「配置」而是「迁移」。放在前端只会诱导误操作。</li>
     *   <li><b>凭据与安全边界</b>——密钥、连接串、工具白名单的删除权限。</li>
     * </ol>
     */
    BACKEND_ONLY;

    /** 前端是否应该展示这个配置项。 */
    public boolean visibleInUi() {
        return this != BACKEND_ONLY;
    }

    /** 保存后是否立即生效（不需要迁移流程）。 */
    public boolean hotReloadable() {
        return this == RUNTIME_HOT;
    }
}
