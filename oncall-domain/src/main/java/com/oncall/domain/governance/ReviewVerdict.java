package com.oncall.domain.governance;

/**
 * 双人复核的判定结果。
 *
 * <p>刻意是<b>封闭的五个值</b>而不是布尔：调用方必须按原因映射到不同的
 * HTTP 状态码（410 / 403 / 409），而且这五种拒绝<b>不能互相混淆</b>——
 * 「过期了请重新发起」和「你不能复核自己的单」是两件完全不同的事，
 * 前者要重走流程，后者要换人。合成一个布尔就会在 UI 上变成同一句"操作失败"。
 */
public enum ReviewVerdict {

    /** 复核通过，可以执行变更。 */
    ALLOWED,

    /** 待复核单已过期。必须重新发起——见 {@link ReviewRequest#expiresAtMillis()} 的说明。 */
    EXPIRED,

    /**
     * 复核者角色不够。
     *
     * <p><b>必须在 {@link #STALE} 之前判定</b>：STALE 的提示信息里含
     * <b>当前生效值</b>，把它返回给一个无权复核的人就是信息泄露。
     * 这条先后关系有测试守着，见 {@code TwoPersonReviewTest}。
     */
    NOT_AUTHORIZED,

    /** 复核者就是发起人。「双人」的意义在于两个独立判断，同一个人点两次不算。 */
    SELF_APPROVAL,

    /**
     * 发起之后、复核之前，被改的对象已经变了。
     *
     * <p>复核者看到的"当前值"与发起人当时看到的不一致，
     * 这次复核的判断依据已经失效，必须重新发起。
     */
    STALE
}
